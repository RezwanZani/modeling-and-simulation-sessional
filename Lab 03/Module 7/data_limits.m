% data_limits.m
% TOPIC: Finding the minimum and maximum values that specific data types can store.

% Find the largest possible value for an 8-bit unsigned integer
intmax('uint8')

% Find the smallest possible value for an 8-bit unsigned integer
intmin('uint8')

% Find the smallest possible value for a 32-bit unsigned integer
intmin('uint32')

% Find the smallest possible value for a 32-bit signed integer
intmin('int32')

% Find the largest number that single precision can store
realmax('single')

% Find the smallest positive value that single precision can store
realmin('single')
